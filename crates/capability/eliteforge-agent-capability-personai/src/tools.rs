    struct DenySearch;
    #[async_trait]
    impl ToolPolicy for DenySearch {
        async fn evaluate(
            &self,
            invocation: &ToolInvocationContext<'_>,
        ) -> Result<ToolPolicyDecision, AgentError> {
            Ok(if invocation.descriptor.id == "personai.search" {
                ToolPolicyDecision::Deny("search disabled by host".into())
            } else {
                ToolPolicyDecision::Allow
            })
        }
    }
    #[tokio::test]
    async fn discovery_respects_host_policy_and_logout() {
        let server = Server::start().await;
        let (connection, context) = connection(&server).await;
        let script = Script {
            requests: Arc::default(),
            replies: Arc::new(Mutex::new(VecDeque::from([
                call("tool_search", json!({"query":"personai_search"})),
                call("personai_search", json!({"query":"rust"})),
                ChatResponse::text("denied"),
                call("tool_search", json!({"query":"personai"})),
                ChatResponse::text("logged out"),
            ]))),
        };
        let pack = crate::PersonAiCapabilityPack::new(connection.clone());
        // Exercise composition with a host-owned, unified discovery catalog.
        let discovery =
            eliteforge_agent_official_plugin_tools_discovery::ToolDiscoveryPlugin::new()
                .provider(pack.tools());
        let agent = TestBuilder::new()
            .capability_pack(pack.without_tools())
            .plugin(discovery)
            .plugin(eliteforge_agent_test_support::TestStoragePlugin::default())
            .plugin(ChatModelPlugin::new(script.clone()))
            .plugin(ToolPolicyPlugin::new("host.policy", DenySearch))
            .build()
            .await
            .unwrap();
        agent
            .run(RunRequest::new("denied", "search"))
            .await
            .unwrap();
        let requests = script.requests.lock().unwrap().clone();
        assert!(
            requests
                .last()
                .unwrap()
                .messages
                .iter()
                .any(|m| m.content.text().contains("search disabled by host"))
        );
        assert!(
            !server
                .requests
                .lock()
                .unwrap()
                .iter()
                .any(|r| r.contains(" /api/v1/search "))
        );
        context.logout();
        agent
            .run(RunRequest::new("logged-out", "search"))
            .await
            .unwrap();
        let requests = script.requests.lock().unwrap().clone();
        assert!(
            requests
                .last()
                .unwrap()
                .messages
                .iter()
                .any(|m| m.content.text().contains("\"matched\":0"))
        );
        agent.close().await;
        connection.close().await.unwrap();
    }

    #[tokio::test]
    async fn invalid_inputs_and_account_changes_never_dispatch_remote_calls() {
        let server = Server::start().await;
        let (connection, context) = connection(&server).await;
        let binding = connection.models.bind_current().unwrap();
        let snapshot = connection.sync.snapshot().await;
        let count = server.requests.lock().unwrap().len();
        for (operation, input) in [
            (Operation::Search, json!({"query":" ","count":1})),
            (Operation::Search, json!({"query":"rust","count":21})),
            (
                Operation::GenerateImage,
                json!({"prompt":"cat","model":"missing"}),
            ),
            (Operation::GenerateImage, json!({"prompt":"cat","count":0})),
            (
                Operation::DetectImage,
                json!({"image_url":"file:///private/image.png"}),
            ),
            (Operation::DetectText, json!({"text":" "})),
            (Operation::QueryImage, json!({"task_id":" "})),
        ] {
            let tool = PersonAiTool {
                operation,
                binding: binding.clone(),
                snapshot: snapshot.clone(),
            };
            assert!(tool.execute(input).await.is_err());
        }
        assert_eq!(server.requests.lock().unwrap().len(), count);
        let account = context.current().unwrap();
        context.publish(AccountContext {
            account_scope: "bob".into(),
            revision: 2,
            authorization: account.authorization.clone(),
        });
        let tool = PersonAiTool {
            operation: Operation::QueryImage,
            binding,
            snapshot,
        };
        assert!(
            tool.execute(json!({"task_id":"image-task"}))
                .await
                .unwrap_err()
                .to_string()
                .contains("changed")
        );
        context.logout();
        assert!(connection.models.bind_current().is_err());
        assert!(
            !server
                .requests
                .lock()
                .unwrap()
                .iter()
                .any(|r| r.contains("/multimedia/tasks/"))
        );
        connection.close().await.unwrap();
        assert!(tool.execute(json!({"task_id":"image-task"})).await.is_err());
    }
