/// Static schemas for host catalogs and permission selection; no credentials or network access.
pub fn personai_tool_catalog() -> Vec<ToolDescriptor> {
    OPERATIONS.iter().map(|op| op.descriptor()).collect()
}

#[derive(Clone)]
pub struct PersonAiToolProvider {
    connection: Arc<PersonAiConnection>,
}
impl PersonAiToolProvider {
    pub fn new(connection: Arc<PersonAiConnection>) -> Self {
        Self { connection }
    }
}

#[derive(Clone, Copy)]
enum Operation {
    Search,
    GenerateImage,
    QueryImage,
    DetectText,
    DetectImage,
}
impl Operation {
    fn descriptor(self) -> ToolDescriptor {
        let string = json!({"type":"string", "minLength":1});
        let (name, description, required, properties) = match self {
            Self::Search => (
                "search",
                "Search the web through PersonAI. Returns titles, URLs and snippets. 搜索网页。",
                vec!["query"],
                json!({"query":string,"count":{"type":"integer","minimum":1,"maximum":20}}),
            ),
            Self::GenerateImage => (
                "generate_image",
                "Submit asynchronous image generation through PersonAI. Returns a task ID; use personai_query_image until completed. 生成图片。",
                vec!["prompt"],
                json!({"prompt":string,"model":string,"size":string,"quality":string,"count":{"type":"integer","minimum":1,"maximum":10}}),
            ),
            Self::QueryImage => (
                "query_image",
                "Query a PersonAI image generation task using its task_id. Returns status, progress and result image URLs. 查询图片任务。",
                vec!["task_id"],
                json!({"task_id":string}),
            ),
            Self::DetectText => (
                "detect_text",
                "Detect whether text was generated by AI using PersonAI AIGC detection. 检测 AI 文本。",
                vec!["text"],
                json!({"text":string,"model":string}),
            ),
            Self::DetectImage => (
                "detect_image",
                "Detect whether an image was generated by AI using PersonAI AIGC detection. Provide image_url (HTTP(S)) or image_base64. 检测 AI 图片。",
                vec![],
                json!({"image_url":string,"image_base64":string,"model":string}),
            ),
        };
        let mut descriptor = ToolDescriptor::new(
            format!("personai.{name}"),
            format!("personai_{name}"),
            description,
            json!({"type":"object","additionalProperties":false,"required":required,"properties":properties}),
        );
        if matches!(self, Self::DetectImage) {
            descriptor.input_schema["oneOf"] =
                json!([{"required":["image_url"]},{"required":["image_base64"]}]);
        }
        descriptor.with_operation_kind(if matches!(self, Self::GenerateImage) {
            eliteforge_agent_core::ToolOperationKind::Command
        } else {
            eliteforge_agent_core::ToolOperationKind::Query
        })
    }
}
const OPERATIONS: [Operation; 5] = [
    Operation::Search,
    Operation::GenerateImage,
    Operation::QueryImage,
    Operation::DetectText,
    Operation::DetectImage,
];

#[async_trait]
impl ToolProvider for PersonAiToolProvider {
    fn descriptors(&self) -> Option<Vec<ToolDescriptor>> {
        Some(personai_tool_catalog())
    }
    async fn lease(&self, context: &RunContext) -> Result<ToolLease, AgentError> {
        context.check_cancelled()?;
        // Logout does not disable other tools or prevent a local Agent from running.
        let Ok(binding) = self.connection.models.bind_current() else {
            return Ok(ToolLease::new(vec![]));
        };
        let snapshot = self.connection.sync.snapshot().await.filter(|snapshot| {
            snapshot.account_scope == binding.account_scope()
                && snapshot.account_revision == binding.account_revision()
        });
        Ok(ToolLease::new(
            OPERATIONS
                .iter()
                .map(|op| {
                    ToolBinding::new(
                        op.descriptor(),
                        PersonAiTool {
                            operation: *op,
                            binding: binding.clone(),
                            snapshot: snapshot.clone(),
                        },
                    )
                })
                .collect(),
        ))
    }
}

struct PersonAiTool {
    operation: Operation,
    binding: Arc<BoundPersonAiModels>,
    snapshot: Option<Arc<PersonAiDiscoverySnapshot>>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SearchInput {
    query: String,
    count: Option<i32>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct ImageInput {
    prompt: String,
    model: Option<String>,
    size: Option<String>,
    quality: Option<String>,
    count: Option<u32>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct QueryInput {
    task_id: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct TextInput {
    text: String,
    model: Option<String>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct DetectionImageInput {
    image_url: Option<String>,
    image_base64: Option<String>,
    model: Option<String>,
}
fn failed(error: impl std::fmt::Display) -> ToolError {
    ToolError::Failed(error.to_string())
}
fn parse<T: serde::de::DeserializeOwned>(value: Value) -> Result<T, ToolError> {
    serde_json::from_value(value).map_err(failed)
}
fn nonempty(value: &str) -> Result<(), ToolError> {
    if value.trim().is_empty() {
        Err(failed("input must not be empty"))
    } else {
        Ok(())
    }
}
impl PersonAiTool {
    fn model(&self, requested: Option<String>, media_type: i32) -> Result<String, ToolError> {
        let available = self
            .snapshot
            .as_ref()
            .and_then(|s| s.media.get(&media_type));
        available.and_then(|models| models.iter().find(|m| requested.as_ref().is_none_or(|id| id == &m.id)))
            .map(|m| m.id.clone()).ok_or_else(|| failed("PersonAI model unavailable for this operation; refresh discovery or select an available model"))
    }
    async fn execute(&self, arguments: Value) -> Result<Value, ToolError> {
        use crate::sdk::multimedia::MediaType;
        self.binding.ensure_current().map_err(failed)?;
        match self.operation {
            Operation::Search => {
                let input: SearchInput = parse(arguments)?;
                nonempty(&input.query)?;
                if input.count.is_some_and(|n| !(1..=20).contains(&n)) {
                    return Err(failed("count must be 1..20"));
                }
                let response = self
                    .binding
                    .search(&input.query, input.count)
                    .await
                    .map_err(failed)?;
                let results: Vec<_> = response.results.unwrap_or_default().into_iter().map(|item|
                    json!({"title":item.title,"url":item.url,"snippet":item.snippet,"source":item.source})).collect();
                Ok(
                    json!({"query":response.query,"count":response.count,"results":results,"provider_code":response.provider_code}),
                )
            }
            Operation::GenerateImage => {
                let input: ImageInput = parse(arguments)?;
                nonempty(&input.prompt)?;
                let count = input.count.unwrap_or(1);
                if !(1..=10).contains(&count) {
                    return Err(failed("count must be 1..10"));
                }
                let model = self.model(input.model, MediaType::IMAGE)?;
                let result = ImageGenerationModel::submit(
                    self.binding.as_ref(),
                    &model,
                    ImageGenerationRequest {
                        choice: ModelChoice::default(),
                        prompt: input.prompt,
                        size: input.size,
                        count,
                        quality: input.quality,
                        provider_options: Default::default(),
                    },
                )
                .await
                .map_err(failed)?;
                Ok(json!({"task_id":result.id,"job":result}))
            }
            Operation::QueryImage => {
                let input: QueryInput = parse(arguments)?;
                nonempty(&input.task_id)?;
                let job = ImageJob {
                    model: self.binding.model_ref(""),
                    protocol: "personai.multimedia".into(),
                    id: input.task_id,
                    binding_id: None,
                    status: ModelJobStatus::Queued,
                    progress: None,
                    images: vec![],
                    error: None,
                };
                let result = ImageGenerationModel::query(self.binding.as_ref(), &job)
                    .await
                    .map_err(failed)?;
                Ok(json!({"task_id":result.id,"job":result}))
            }
            Operation::DetectText => {
                let input: TextInput = parse(arguments)?;
                nonempty(&input.text)?;
                let model = self.model(input.model, MediaType::AIGC_TEXT_DETECTION)?;
                serde_json::to_value(
                    self.binding
                        .detect(
                            &model,
                            ContentDetectionRequest {
                                choice: ModelChoice::default(),
                                content: input.text.into(),
                            },
                        )
                        .await
                        .map_err(failed)?,
                )
                .map_err(failed)
            }
            Operation::DetectImage => {
                let input: DetectionImageInput = parse(arguments)?;
                let source = match (input.image_url, input.image_base64) {
                    (Some(value), None) => {
                        let url = reqwest::Url::parse(&value).map_err(failed)?;
                        if !matches!(url.scheme(), "http" | "https") || url.host_str().is_none() {
                            return Err(failed("image_url must be HTTP(S)"));
                        }
                        MediaSource::Url(value)
                    }
                    (None, Some(value)) => {
                        use base64::Engine;
                        if value.len() > 12 * 1024 * 1024 {
                            return Err(failed("image_base64 exceeds size limit"));
                        }
                        let bytes = base64::engine::general_purpose::STANDARD
                            .decode(&value)
                            .map_err(|_| failed("invalid image_base64"))?;
                        if bytes.is_empty() {
                            return Err(failed("image_base64 must not be empty"));
                        }
                        MediaSource::Base64(value)
                    }
                    _ => return Err(failed("provide exactly one of image_url or image_base64")),
                };
                let model = self.model(input.model, MediaType::AIGC_IMAGE_DETECTION)?;
                let content = Content::from(vec![ContentBlock::Media {
                    media: MediaContent {
                        mime_type: "image/*".into(),
                        source,
                        name: None,
                        estimated_tokens: None,
                    },
                }]);
                serde_json::to_value(
                    self.binding
                        .detect(
                            &model,
                            ContentDetectionRequest {
                                choice: ModelChoice::default(),
                                content,
                            },
                        )
                        .await
                        .map_err(failed)?,
                )
                .map_err(failed)
            }
        }
    }
}
#[async_trait]
impl Tool for PersonAiTool {
    async fn call(&self, arguments: Value, context: &RunContext) -> Result<ToolOutput, ToolError> {
        if context.is_cancelled() {
            return Err(failed("PersonAI tool cancelled"));
        }
        let value = self.execute(arguments).await?;
        let mut output = ToolOutput::text(value.to_string());
        output.structured = Some(value);
        Ok(output)
    }
}

